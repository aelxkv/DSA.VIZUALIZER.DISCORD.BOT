"""Contract test: run lines written by released versions must keep working.

tests/golden/run_lines_v1.txt was generated by v1.0.0. Never edit it to make a
test pass; if this fails, the new code broke old threads (`/step` would stop
working for them).
"""

from pathlib import Path

import pytest

from core.runner import execute
from core.spec import parse_line

GOLDEN = Path(__file__).parent / "golden" / "run_lines_v1.txt"
LINES = [line for line in GOLDEN.read_text(encoding="utf-8").splitlines() if line.strip()]


def test_golden_file_covers_every_algorithm():
    from core import registry

    assert len(LINES) == len(registry.all_algos())


@pytest.mark.parametrize("line", LINES)
def test_v1_lines_parse_run_and_serialise_identically(line):
    spec = parse_line(f"**Title** · run by someone\n{line}\nℹ️ a note")
    assert f"`{spec.to_line()}`" == line
    run = execute(spec)
    assert run.steps[-1].is_key
