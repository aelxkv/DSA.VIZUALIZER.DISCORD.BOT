"""Tiny helpers for uptime and memory text."""

from __future__ import annotations

import sys


def format_duration(seconds: float) -> str:
    """1h 02m style text: '45s', '12m 5s', '3h 7m', '2d 4h'."""
    total = max(int(seconds), 0)
    days, rem = divmod(total, 86400)
    hours, rem = divmod(rem, 3600)
    minutes, secs = divmod(rem, 60)
    if days:
        return f"{days}d {hours}h"
    if hours:
        return f"{hours}h {minutes}m"
    if minutes:
        return f"{minutes}m {secs}s"
    return f"{secs}s"


def rss_mb() -> float | None:
    """Current resident memory in MB (Linux/Android), else peak RSS, else None."""
    try:
        with open("/proc/self/status", encoding="ascii", errors="ignore") as handle:
            for line in handle:
                if line.startswith("VmRSS:"):
                    return int(line.split()[1]) / 1024
    except (OSError, ValueError, IndexError):
        pass
    try:
        import resource

        peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        return peak / (1024 * 1024) if sys.platform == "darwin" else peak / 1024
    except (ImportError, OSError):
        return None
